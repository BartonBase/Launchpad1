#!/usr/bin/env node
/**
 * Generates src/lib/generated/idlMeta.ts from the Anchor IDLs in src/lib/generated/idl/
 * (copied verbatim from /workspace/idl/devnet, which matches the DEPLOYED devnet programs byte-for-byte; NOT ../target/idl). Emits instruction + account discriminators and error tables so
 * the hand-written builders/decoders never hard-code magic bytes. Run: `npm run gen:idl`.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, "../src/lib/generated/idl");
const out = path.resolve(here, "../src/lib/generated/idlMeta.ts");
const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

let ts = `/* GENERATED by scripts/gen-idl-meta.mjs from src/lib/generated/idl/*.json. DO NOT EDIT. */\n\n`;
for (const file of ["hybrid_launch.json", "hybrid_vault.json"]) {
  const idl = JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"));
  const n = camel(idl.metadata.name);
  ts += `export const ${n}Address = ${JSON.stringify(idl.address)};\n`;
  ts += `export const ${n}Ix = {\n${idl.instructions.map((i) => `  ${camel(i.name)}: ${JSON.stringify(i.discriminator)},`).join("\n")}\n} as const;\n`;
  ts += `export const ${n}Accounts = {\n${(idl.accounts ?? []).map((a) => `  ${a.name}: ${JSON.stringify(a.discriminator)},`).join("\n")}\n} as const;\n`;
  ts += `export const ${n}Errors: Record<number, { name: string; msg: string }> = {\n${(idl.errors ?? [])
    .map((e) => `  ${e.code}: { name: ${JSON.stringify(e.name)}, msg: ${JSON.stringify(e.msg ?? "")} },`)
    .join("\n")}\n};\n\n`;
}
fs.writeFileSync(out, ts);
console.log("wrote", path.relative(process.cwd(), out));
